import math
import os

# constants representing the species and counts
SP_CHINSTRAP = "Chinstrap"
SP_GENTOO = "Gentoo"
SP_ADELIE = "Adelie"

NUM_CHINSTRAP = 68
NUM_GENTOO = 123
NUM_ADELIE = 151

species_names = [
    SP_CHINSTRAP,
    SP_GENTOO,
    SP_ADELIE
]

species_counts = [
    NUM_CHINSTRAP,
    NUM_GENTOO,
    NUM_ADELIE
]


# locate the Palmer Penguins CSV file
def get_csv_path():
    possible_paths = [
        "PalmerPenguins.csv",
        "/content/PalmerPenguins.csv"
    ]

    for path in possible_paths:
        if os.path.exists(path):
            return path

    raise FileNotFoundError(
        "PalmerPenguins.csv was not found. "
        "Upload it to the Colab Files panel."
    )


# read a specific penguin observation from the CSV file
def read_penguin_row(row_number):
    csv_path = get_csv_path()
    penguin_row = ""

    # open the CSV file and skip the header row
    with open(csv_path, "r") as penguin_file:
        penguin_file.readline()

        current_row = 1

        # search for the requested data row
        for row in penguin_file:
            if current_row == row_number:
                penguin_row = row.strip()
                break

            current_row += 1

    # return the requested row as a string
    return penguin_row


# calculate a species percentage
def calculate_percentage(count, total):
    return count / total * 100


# classify a species by percentage
def classify_species(percent):
    if percent < 25:
        return "small"
    elif percent < 40:
        return "medium"
    else:
        return "large"


# determine the species position
def get_position_description(
    selected_species,
    largest_species,
    smallest_species
):
    if selected_species == largest_species:
        return "largest"
    elif selected_species == smallest_species:
        return "smallest"
    else:
        return "middle-sized"


# display species statistics
def display_species_statistics(
    names,
    counts,
    percentages
):
    for index, species in enumerate(names):
        print(
            f"{species}: {counts[index]} "
            f"({percentages[index]:.2f}%)"
        )


# display one penguin observation
def display_penguin_observation(
    sample_number,
    species,
    bill_length,
    bill_depth,
    body_mass,
    sex
):
    print()
    print("Sample Penguin Observation")
    print()
    print(f"{'Sample Number:':<18}{sample_number}")
    print(f"{'Species:':<18}{species}")
    print(f"{'Bill length:':<18}{bill_length} mm")
    print(f"{'Bill depth:':<18}{bill_depth} mm")
    print(f"{'Body mass:':<18}{body_mass} g")
    print(f"{'Sex:':<18}{sex}")


# process one penguin row
def process_penguin_row(row_number):
    penguin_row = read_penguin_row(row_number)
    penguin_data = penguin_row.split(",")

    sample_number = int(penguin_data[0])
    species = penguin_data[1]
    bill_length = float(penguin_data[2])
    bill_depth = float(penguin_data[3])
    body_mass = int(penguin_data[5])
    sex = penguin_data[6]

    display_penguin_observation(
        sample_number,
        species,
        bill_length,
        bill_depth,
        body_mass,
        sex
    )


def main():
    # calculate dataset statistics
    total_species = len(species_names)
    total_penguins = sum(species_counts)
    average_penguins = total_penguins / total_species
    average_rounded = math.ceil(average_penguins)

    species_percentages = []

    for count in species_counts:
        percent = calculate_percentage(
            count,
            total_penguins
        )
        species_percentages.append(percent)

    largest_count = max(species_counts)
    smallest_count = min(species_counts)

    largest_index = species_counts.index(
        largest_count
    )
    smallest_index = species_counts.index(
        smallest_count
    )

    largest_species = species_names[
        largest_index
    ]
    smallest_species = species_names[
        smallest_index
    ]

    # display dataset statistics
    print("Introducing the Palmer Penguins:")
    print(f" {species_names[0]}!")
    print(f" {species_names[1]}!")
    print("and last but not least...")
    print(f" {species_names[2]}!")

    print(
        f"There are a total of {total_species} "
        f"penguin species in this dataset."
    )
    print(
        f"There are a total of {total_penguins} "
        f"penguins in the dataset."
    )
    print(
        f"The average number of penguins per species "
        f"is {average_penguins:.1f}."
    )
    print(
        f"The average rounded up is "
        f"{average_rounded} penguins."
    )

    display_species_statistics(
        species_names,
        species_counts,
        species_percentages
    )

    print(
        f"The species with the most observations is "
        f"{largest_species} with "
        f"{largest_count} penguins."
    )
    print(
        f"The species with the fewest observations is "
        f"{smallest_species} with "
        f"{smallest_count} penguins."
    )

    # process two sample observations
    process_penguin_row(1)
    process_penguin_row(342)

    # create a list of sample row numbers
    sample_rows = [1, 2, 3, 4, 5]

    # collect body masses from the CSV data
    body_masses = []

    for row_number in sample_rows:
        penguin_row = read_penguin_row(row_number)
        penguin_data = penguin_row.split(",")

        body_mass = int(penguin_data[5])
        body_masses.append(body_mass)

    print()
    print("Sample Body Masses")
    print(body_masses)

    # calculate summary statistics
    number_observations = len(body_masses)
    total_body_mass = sum(body_masses)
    smallest_body_mass = min(body_masses)
    largest_body_mass = max(body_masses)
    average_body_mass = (
        total_body_mass / number_observations
    )

    print()
    print("Body Mass Summary")
    print(
        f"Observations:       "
        f"{number_observations}"
    )
    print(
        f"Total body mass:    "
        f"{total_body_mass} g"
    )
    print(
        f"Smallest body mass: "
        f"{smallest_body_mass} g"
    )
    print(
        f"Largest body mass:  "
        f"{largest_body_mass} g"
    )
    print(
        f"Average body mass:  "
        f"{average_body_mass:.2f} g"
    )

    # associate species names with observation counts
    species_dictionary = {
        SP_CHINSTRAP: NUM_CHINSTRAP,
        SP_GENTOO: NUM_GENTOO,
        SP_ADELIE: NUM_ADELIE
    }

    print()
    print("Species Counts Using a Dictionary")

    for species in species_dictionary:
        count = species_dictionary[species]
        print(f"{species}: {count}")

    # interactive species exploration
    valid_selections = 0

    print()
    print("Explore the Palmer Penguins")

    species_choice = input(
        "Enter Chinstrap, Gentoo, Adelie, or Done: "
    )

    while species_choice != "Done":

        if species_choice not in species_names:
            print(
                f"{species_choice} is not one of the "
                f"species in this dataset."
            )

        else:
            selected_index = species_names.index(
                species_choice
            )

            selected_species = species_names[
                selected_index
            ]
            selected_count = species_counts[
                selected_index
            ]
            selected_percent = species_percentages[
                selected_index
            ]

            size_category = classify_species(
                selected_percent
            )

            position_description = (
                get_position_description(
                    selected_species,
                    largest_species,
                    smallest_species
                )
            )

            if selected_count > average_penguins:
                average_position = "above"
            else:
                average_position = "below"

            valid_selections += 1

            print(
                f"{selected_species} has "
                f"{selected_count} observations, "
                f"representing "
                f"{selected_percent:.2f}% "
                f"of the dataset."
            )
            print(
                f"{selected_species} is classified "
                f"as a {size_category} species group."
            )
            print(
                f"{selected_species} is the "
                f"{position_description} species group."
            )
            print(
                f"Its observation count is "
                f"{average_position} the dataset "
                f"average of {average_penguins:.1f}."
            )

        species_choice = input(
            "Enter Chinstrap, Gentoo, Adelie, or Done: "
        )

    print(
        f"You explored {valid_selections} "
        f"valid species."
    )
    print("Exploration complete.")


main()